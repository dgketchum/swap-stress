# §3.5 Aggregation & multiplicity
# ---------------------------------------------------------------------------


def site_bootstrap_ci(
    values,
    n_boot: int = DEFAULT_N_BOOT,
    alpha: float = 0.05,
    statistic=np.median,
    seed: int = 0,
):
    """Bootstrap CI for a statistic over site-level values (§3.5).

    Resamples *sites* (the independent unit) with replacement. Returns
    ``(point, lo, hi)`` where ``point`` is the statistic on the observed values
    and ``lo/hi`` are the (alpha/2, 1-alpha/2) percentiles of the bootstrap
    distribution. All-NaN if fewer than 3 finite values.
    """
    values = np.asarray(values, dtype=np.float64)
    values = values[np.isfinite(values)]
    n = len(values)
    if n < 3:
        return np.nan, np.nan, np.nan
    rng = np.random.default_rng(seed)
    point = float(statistic(values))
    boot = np.empty(n_boot, dtype=np.float64)
    for i in range(n_boot):
        sample = values[rng.integers(0, n, size=n)]
        boot[i] = statistic(sample)
    lo = float(np.percentile(boot, 100 * alpha / 2))
    hi = float(np.percentile(boot, 100 * (1 - alpha / 2)))
    return point, lo, hi


def benjamini_hochberg(pvals, alpha: float = 0.05):
    """Benjamini–Hochberg FDR control (§3.5).

    Returns ``(rejected_mask, adjusted_pvals)`` aligned to the input order.
    NaN p-values are never rejected and pass through as NaN adjusted values.
    """
    pvals = np.asarray(pvals, dtype=np.float64)
    n_total = len(pvals)
    rejected = np.zeros(n_total, dtype=bool)
    adjusted = np.full(n_total, np.nan, dtype=np.float64)

    finite_idx = np.where(np.isfinite(pvals))[0]
    m = len(finite_idx)
    if m == 0:
        return rejected, adjusted

    p = pvals[finite_idx]
    order = np.argsort(p, kind="stable")
    ranked = p[order]
    ranks = np.arange(1, m + 1)

    # Adjusted p-values (step-up), enforced monotone non-decreasing.
    adj_sorted = ranked * m / ranks
    adj_sorted = np.minimum.accumulate(adj_sorted[::-1])[::-1]
    adj_sorted = np.clip(adj_sorted, 0.0, 1.0)

    adj = np.empty(m, dtype=np.float64)
    adj[order] = adj_sorted
    adjusted[finite_idx] = adj

    # Rejection: largest k with p_(k) <= k/m * alpha.
    below = np.where(ranked <= ranks / m * alpha)[0]
    if len(below) > 0:
        k_max = below.max()
        reject_sorted = np.zeros(m, dtype=bool)
        reject_sorted[: k_max + 1] = True
        rej = np.empty(m, dtype=bool)
        rej[order] = reject_sorted
        rejected[finite_idx] = rej
    return rejected, adjusted


def sign_test(values, popmean: float = 0.0, alternative: str = "greater") -> dict:
    """Binomial sign test that per-site values exceed ``popmean`` (§3.3/§3.5).

    Reports the fraction of positive deltas and a binomial p-value vs the 50%
    (or, for the partial-F-rate use case, an explicit chance rate via
    :func:`binomial_rate_test`).
    """
    values = np.asarray(values, dtype=np.float64)
    values = values[np.isfinite(values)]
    n = len(values)
    if n == 0:
        return {"n": 0, "frac_pos": np.nan, "p": np.nan}
    n_pos = int(np.sum(values > popmean))
    n_effective = int(np.sum(values != popmean))
    if n_effective == 0:
        return {"n": n, "frac_pos": 0.0, "p": 1.0}
    res = sp_stats.binomtest(n_pos, n_effective, p=0.5, alternative=alternative)
    return {"n": n, "frac_pos": n_pos / n, "p": float(res.pvalue)}


def binomial_rate_test(
    n_success: int, n_trials: int, rate: float = 0.05, alternative: str = "greater"
) -> float:
    """Binomial test that ``n_success/n_trials`` exceeds a chance ``rate`` (§3.3).

    Used for "fraction of sites with per-site partial-F significant, vs the 5%
    chance rate."
    """
    if n_trials == 0:
        return np.nan
    res = sp_stats.binomtest(n_success, n_trials, p=rate, alternative=alternative)
    return float(res.pvalue)


def wilcoxon_greater(values) -> float:
    """One-sided Wilcoxon signed-rank p that the median of ``values`` > 0.

    Kept for parity with the legacy tables (reported *alongside* the CV/perm
    tests, never as the sole evidence)."""
    values = np.asarray(values, dtype=np.float64)
    values = values[np.isfinite(values)]
    if len(values) < 5:
        return np.nan
    try:
        _, p = sp_stats.wilcoxon(values, alternative="greater")
    except ValueError:
        return np.nan
    return float(p)
